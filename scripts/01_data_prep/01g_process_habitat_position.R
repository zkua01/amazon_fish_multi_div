# =============================================================================
# Script:  01g_process_habitat_position.R
# Project: Amazon multidimensional biodiversity
# Purpose: Process habitat, fragmentation/isolation, and basin position
#          variables for each subdrainage basin. Includes elevation metrics,
#          sea-level rise proxies, slope, waterfalls, network density, soil
#          diversity, land cover diversity, water color, position metrics,
#          and sampling effort.
#
# Inputs:
#   output/intermediate/basins_historical_climate.rds         (from 01f)
#   data/raw/env/habitat/wc2.1_5m_elev.tif                    (WorldClim elevation)
#   data/raw/env/habitat/riverine_network/amzrivnet_clip.shp  (river network)
#   data/raw/env/habitat/riverine_network/amztrbmth_v.shp     (tributary mouths)
#   data/raw/env/habitat/riverine_network/amztrbsrc_v.shp     (tributary sources)
#   data/processed/slope15.csv                                (ArcGIS-derived)
#   data/processed/soil_types.csv                             (ArcGIS-derived)
#   data/processed/land_cover.csv                             (ArcGIS-derived)
#   data/processed/water_color.csv                            (ArcGIS-derived)
#   data/processed/waterfalls.csv                             (ArcGIS-derived)
#   data/processed/pebas_lake.csv                             (ArcGIS-derived)
#   data/processed/amazon_occurrences_clean.csv               (from 01c)
#
# Outputs:
#   output/intermediate/basins_full_environment.rds    (full basins object)
#   output/intermediate/pca_elev.csv                   (elevation PCA scores)
#
# Non-reproducible steps:
#   The following CSVs were generated in ArcGIS Pro and cannot be regenerated
#   from this script alone. They are provided as bundled data files:
#   - slope15.csv:      % area with slope >= 15 degrees (from DEM)
#   - soil_types.csv:   Soil type proportions per basin (HWSD, Caspari & Schad 2022)
#   - land_cover.csv:   Land cover proportions per basin (ESA CCI, 2017)
#   - water_color.csv:  Water color classification (Venticinque et al. 2016)
#   - waterfalls.csv:   Waterfall counts per basin (Altenau et al. 2021)
#   - pebas_lake.csv:   Pebas Lake basin indicator (Hoorn et al. 2010)
#
# Dependencies: terra, sf, exactextractr, tidyverse, vegan, paran, here
# =============================================================================

library(terra)
library(sf)
library(exactextractr)
library(tidyverse)
library(vegan)
library(paran)
library(here)

set.seed(123)

# --- Paths -------------------------------------------------------------------
inter_dir    <- here("output", "intermediate")
habitat_dir  <- here("data", "raw", "env", "habitat")
processed_dir <- here("data", "processed")
dir.create(inter_dir, showWarnings = FALSE, recursive = TRUE)

# --- Helper functions ----------------------------------------------------------
read_transform <- function(path, target_crs = 5880) {
  obj <- st_read(path, quiet = TRUE)
  if (st_crs(obj) != target_crs) {
    obj <- st_transform(obj, target_crs)
  }
  obj
}

read_transform_rast <- function(path, target_crs = "EPSG:5880", method = "bilinear") {
  r <- rast(path)
  if (!is.na(crs(r)) && !grepl("5880", crs(r))) {
    message("Reprojecting raster: ", basename(path))
    r <- project(r, target_crs, method = method)
  }
  r
}

# --- 1. Load basins with historical climate (from 01f) --------------------------
message("Loading basins with historical climate data...")
basins <- readRDS(file.path(inter_dir, "basins_historical_climate.rds"))

# =============================================================================
# SECTION A: HISTORICAL / FRAGMENTATION
# =============================================================================

# --- 2. Pebas Lake indicator ----------------------------------------------------
# NOTE: This CSV was generated by overlaying basin polygons with the Pebas Lake
#       extent from Hoorn et al. (2010). Non-reproducible from this script.
message("Loading Pebas Lake indicator...")
pebas <- read.csv(file.path(processed_dir, "pebas_lake.csv"))
basins <- basins |>
  mutate(PebasLake = ifelse(SBD_CD %in% pebas$SBD_CD, 0, 1))

# --- 3. Elevation metrics --------------------------------------------------------
message("Extracting elevation metrics...")
wc_elev <- read_transform_rast(file.path(habitat_dir, "Elevation/wc2.1_5m_elev.tif"))

basins$elev_mean  <- exact_extract(wc_elev, basins, fun = "mean")
basins$elev_max   <- exact_extract(wc_elev, basins, fun = "max")
basins$elev_min   <- exact_extract(wc_elev, basins, fun = "min")
basins$elev_sd    <- exact_extract(wc_elev, basins,
                                   fun = function(values, coverage_fraction) {
                                     sd(values, na.rm = TRUE)
                                   })
basins$elev_range <- basins$elev_max - basins$elev_min

# --- 4. Proportion of area above 1000 m (arcsine transformed) -------------------
message("Calculating proportion above 1000 m...")
calc_elev_prop <- function(elevation_raster, basins_sf) {
  exact_extract(elevation_raster, basins_sf, function(values, coverage_fraction) {
    if (all(is.na(values))) return(NA)
    valid_values <- values[!is.na(values)]
    sum(valid_values > 1000) / length(valid_values)
  })
}

basins$elev_prop_above_1000m <- calc_elev_prop(wc_elev, basins)
basins$elev_prop_above_1000m <- asin(sqrt(basins$elev_prop_above_1000m))

# --- 5. Sea-level rise proxies (SLR 25 m and 100 m) ------------------------------
message("Calculating SLR proxies...")
calc_elev_slr <- function(elevation_raster, basins_sf, sea_level) {
  exact_extract(elevation_raster, basins_sf, function(values, coverage_fraction) {
    if (all(is.na(values))) return(NA)
    valid_values <- values[!is.na(values)]
    sum(valid_values <= sea_level) / length(valid_values)
  })
}

basins$slr25m  <- asin(sqrt(calc_elev_slr(wc_elev, basins, 25)))
basins$slr100m <- asin(sqrt(calc_elev_slr(wc_elev, basins, 100)))

rm(wc_elev)
gc()

# --- 6. Slope >= 15 degrees (ArcGIS-derived) -------------------------------------
# NOTE: This CSV was generated in ArcGIS Pro from the WorldClim DEM.
#       It represents the proportion of each basin with slope >= 15 degrees.
#       Non-reproducible from this script.
message("Loading slope data...")
slope <- read.csv(file.path(processed_dir, "slope15.csv"))
basins$slope15 <- slope$slope15_pct[match(basins$SBD_CD, slope$SBD_CD)]

# --- 7. PCA on elevation variables ------------------------------------------------
message("Running PCA: Elevation...")
basins_elev <- st_drop_geometry(basins)
elevprop <- basins_elev |>
  dplyr::select(elev_mean, elev_max, elev_min, elev_sd, elev_range,
                elev_prop_above_1000m, slope15)

# Replace NAs with small value (documented imputation)
n_na <- sum(is.na(elevprop))
if (n_na > 0) {
  message("Replacing ", n_na, " NA values in elevation data with 0.001")
  elevprop[is.na(elevprop)] <- 0.001
}

elevprop_sc <- as.data.frame(scale(elevprop))

paran_elev <- paran(as.matrix(elevprop_sc), iterations = 5000)
pca_elev   <- prcomp(elevprop_sc)

pca_elev_scores <- as.data.frame(pca_elev$x) |>
  dplyr::select(1:paran_elev$Retained) |>
  dplyr::rename_with(~ paste(.x, "Elev", sep = "_")) |>
  rownames_to_column(var = "SBD_CD")

write.csv(pca_elev_scores, file.path(inter_dir, "pca_elev.csv"), row.names = FALSE)
message("PCA Elevation: ", paran_elev$Retained, " components retained.")

# --- 8. Waterfalls (ArcGIS-derived) ------------------------------------------------
# NOTE: Waterfall counts extracted from SWORD database (Altenau et al. 2021)
#       via spatial intersection in ArcGIS Pro. Non-reproducible from this script.
message("Loading waterfall data...")
waterfalls <- read.csv(file.path(processed_dir, "waterfalls.csv"))
basins$waterfalls <- waterfalls$COUNT_hfalls_id[match(basins$SBD_CD, waterfalls$SBD_CD)]
basins$waterfalls[is.na(basins$waterfalls)] <- 0

# =============================================================================
# SECTION B: HABITAT
# =============================================================================

# --- 9. Network density (river length / basin area) ---------------------------------
message("Calculating network density...")
streams <- read_transform(file.path(habitat_dir, "riverine_network/amzrivnet_clip.shp"))
basins <- st_make_valid(basins)
streams <- st_make_valid(streams)

strbas_intersect <- st_intersection(streams, basins)
strbas_intersect$length <- st_length(strbas_intersect)

strbas_length <- strbas_intersect |>
  st_drop_geometry() |>
  group_by(SBD_CD) |>
  summarise(total_length = sum(length, na.rm = TRUE), .groups = "drop")

basins$NetworkDensity <- strbas_length$total_length[match(basins$SBD_CD, strbas_length$SBD_CD)] /
  1000 / basins$AREA

# --- 10. Soil diversity (ArcGIS-derived, Shannon index) --------------------------------
# NOTE: Soil type proportions were calculated in ArcGIS Pro by intersecting the
#       Harmonized World Soil Database (Caspari & Schad 2022) with basin polygons.
#       Non-reproducible from this script.
message("Calculating soil diversity...")
soil <- read.csv(file.path(processed_dir, "soil_types.csv"))
colnames(soil)[1] <- "SBD_CD"

soil_wide <- soil |>
  pivot_wider(names_from = SU_SYMBOL, values_from = Prop, values_fill = 0) |>
  column_to_rownames("SBD_CD")

basins$soilDiv <- diversity(as.matrix(soil_wide), index = "shannon")

# --- 11. Land cover diversity (ArcGIS-derived, Shannon index) ---------------------------
# NOTE: Land cover proportions were calculated in ArcGIS Pro from ESA CCI data (2017).
#       Non-reproducible from this script.
message("Calculating land cover diversity...")
lc <- read.csv(file.path(processed_dir, "land_cover.csv"))
lc <- lc[, c("SBD_CD", "gridcode", "Prop")]

lc_wide <- lc |>
  pivot_wider(names_from = gridcode, values_from = Prop, values_fill = 0) |>
  column_to_rownames("SBD_CD")

basins$LCDiv <- diversity(as.matrix(lc_wide), index = "shannon")

# --- 12. Water color (ArcGIS-derived, categorical) ----------------------------------------
# NOTE: Water color classification from Venticinque et al. (2016).
#       Non-reproducible from this script.
message("Loading water color data...")
wc_color <- read.csv(file.path(processed_dir, "water_color.csv"))
basins$WaterColor <- factor(wc_color$type[match(basins$SBD_CD, wc_color$SBD_CD)])

# =============================================================================
# SECTION C: POSITION
# =============================================================================

# --- 13. Distance to river mouth ----------------------------------------------------------
message("Calculating distance to river mouth...")
amztrbmth <- read_transform(file.path(habitat_dir, "riverine_network/amztrbmth_v.shp"))
basins_crs <- st_crs(basins)
amztrbmth <- st_transform(amztrbmth, crs = basins_crs)

subbasins_centroids <- st_centroid(basins)
distances <- st_distance(subbasins_centroids, amztrbmth[1, ])
basins$DistMouth_km <- as.numeric(distances) / 1000

# --- 14. Tributary position ------------------------------------------------------------------
# Tributary position is encoded in the MTRIB_CD field of the basin shapefile.
# Lower values = closer to river mouth; higher values = closer to source.
basins$TributaryPosition <- basins$MTRIB_CD

# =============================================================================
# SECTION D: SAMPLING EFFORT
# =============================================================================

# --- 15. Sampling effort (unique coordinate pairs per basin area) ----------------------------
message("Calculating sampling effort...")
occ <- read.csv(file.path(processed_dir, "amazon_occurrences_clean.csv"))

sampling <- occ |>
  mutate(sample_event = paste0(Longitude.X, Latitude.Y)) |>
  group_by(SubDrainage.Code) |>
  summarise(sample_count = n_distinct(sample_event), .groups = "drop")

basins <- basins |>
  left_join(sampling, by = c("SBD_CD" = "SubDrainage.Code")) |>
  mutate(sample_area = sample_count / AREA)

# =============================================================================
# E. EXTRACT ONLY RETAINED VARIABLES
# =============================================================================

# --- 16. Build final output table (no geometry, only retained columns) ---
message("Extracting retained variables...")

if (!all(c("CENT_X", "CENT_Y") %in% names(basins))) {
  # Fallback: compute centroids in WGS84 if columns are missing
  message("CENT_X/CENT_Y not found in basins. Computing in WGS84...")
  centroids_wgs84 <- basins |>
    st_transform(crs = 4326) |>
    st_centroid() |>
    st_coordinates() |>
    as.data.frame()
  basins$CENT_X <- centroids_wgs84$X
  basins$CENT_Y <- centroids_wgs84$Y
}

# Validate coordinate ranges (Amazon basin: lon ~-75 to -44, lat ~-16 to 5)
stopifnot(all(basins$CENT_X > -80 & basins$CENT_X < -40, na.rm = TRUE))
stopifnot(all(basins$CENT_Y > -20 & basins$CENT_Y < 10, na.rm = TRUE))
message("Coordinate validation passed. CENT_X range: ",
        round(range(basins$CENT_X), 2), " | CENT_Y range: ",
        round(range(basins$CENT_Y), 2))

habitat_position <- data.frame(
  SBD_CD             = basins$SBD_CD,
  CENT_X             = basins$CENT_X,
  CENT_Y             = basins$CENT_Y,
  AREA               = basins$AREA,
  PebasLake          = basins$PebasLake,
  slr25m             = basins$slr25m,
  slr100m            = basins$slr100m,
  waterfalls         = basins$waterfalls,
  NetworkDensity     = basins$NetworkDensity,
  soilDiv            = basins$soilDiv,
  LCDiv              = basins$LCDiv,
  WaterColor         = as.character(basins$WaterColor),
  DistMouth_km       = basins$DistMouth_km,
  TributaryPosition  = basins$TributaryPosition,
  sample_area        = basins$sample_area
)

write.csv(habitat_position,
          file.path(inter_dir, "habitat_position_vars.csv"),
          row.names = FALSE)

message("01g complete. Outputs saved to: ", inter_dir)
message("  - pca_elev.csv (", ncol(pca_elev_scores) - 1, " PC scores)")
message("  - habitat_position_vars.csv (", ncol(habitat_position), " variables)")
